#!/usr/bin/env node
/**
 * dsh-task-alerts — browser-half bundle assembly (contract §7).
 *
 * No bundler, no dependencies. The two sources compiled by
 * `tsc -p tsconfig.client.json` are plain scripts (no import/export), so they
 * are concatenated verbatim inside one `window.__ModuleLoader__.load` factory
 * and the stylesheet is inlined as a JSON string ahead of them. The result is
 * a single file, `lib/client.js`, that the DSH web client can load on its own.
 *
 * Concatenation order is `AlertPanel.js` then `client.js`: AlertPanel only
 * *publishes* onto `window.__DSA__` and never reads it back, while client.ts
 * owns the namespace and reads `window.__DSA__.AlertPanel`. Order does not
 * change correctness either way (both run before the factory returns), but
 * this order keeps every `window.__DSA__` reader downstream of its writer.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..')

const SRC_DIR = join(ROOT, 'build', 'client')
const CSS_PATH = join(ROOT, 'src', 'ui', 'styles.css')
const OUT_JS = join(ROOT, 'lib', 'client.js')
const OUT_DTS = join(ROOT, 'lib', 'client.d.ts')

/**
 * Concatenation order — see the header note.
 *
 * This is an EXPLICIT ORDERED WHITELIST, not a glob. Order matters: every file
 * that only *publishes* onto `window.__DSA__` must come before the file that
 * reads it back. Adding a new `src/ui/*.tsx` therefore REQUIRES adding it here;
 * the completeness guard below fails the build if you forget.
 */
const PARTS = ['AlertPanel.js', 'SettingsForm.js', 'client.js']

const MODULE_ID = 'dsh-task-alerts'

const CLIENT_DTS = `/**
 * dsh-task-alerts — browser (client) half type declaration.
 *
 * Generated by scripts/build-client.mjs. The browser half is a compiled
 * browser module in the \`window.__ModuleLoader__.load({ id, factory })\` form:
 * a normal browser module with full access to fetch/document/window. The loader
 * passes the resolver into the factory — \`factory(require)\` — and the factory's
 * return value IS the module exports; \`react\` is obtained by calling
 * \`require("react")\` inside the factory body.
 */

/** Declarative service dependency of the browser half: the client \`slots\` service. */
export declare const inject: string[];

/**
 * Mounts the glass alert panel and the toast stack on \`shell.overlay\`, starts
 * the \`/task-alerts/state\` poll, binds the in-app stop hotkey and injects the
 * plugin stylesheet. Returns nothing; teardown rides \`ctx.effect\` (with a
 * \`ctx.on('dispose')\` fallback).
 */
export declare function apply(ctx: any): void;

/** The factory's return shape: the browser plugin exports consumed by the loader. */
export interface TaskAlertsClientPlugin {
  inject: string[];
  apply: (ctx: any) => void;
}
`

function fail(message) {
  process.stderr.write(`build-client: ${message}\n`)
  process.exit(1)
}

// ---- 1. inputs -----------------------------------------------------------

const missing = []
for (const name of PARTS) {
  const file = join(SRC_DIR, name)
  if (!existsSync(file)) missing.push(file)
}
if (!existsSync(CSS_PATH)) missing.push(CSS_PATH)
if (missing.length > 0) {
  fail(
    'missing build input(s):\n' +
      missing.map((p) => `  - ${p}`).join('\n') +
      '\nrun `tsc -p tsconfig.client.json` first (it emits build/client/*.js).',
  )
}

const css = readFileSync(CSS_PATH, 'utf8')
if (css.trim().length === 0) fail(`stylesheet is empty: ${CSS_PATH}`)

const sources = PARTS.map((name) => ({
  name,
  text: readFileSync(join(SRC_DIR, name), 'utf8'),
}))

for (const part of sources) {
  if (part.text.trim().length === 0) fail(`compiled source is empty: ${part.name}`)
  if (/^\s*(import|export)\s/m.test(part.text)) {
    fail(
      `${part.name} contains an ESM import/export statement; ` +
        'the concatenation scheme requires plain scripts (contract §7).',
    )
  }
}

// ---- 1b. completeness guard ---------------------------------------------
//
// A source file that compiles but is missing from PARTS never reaches
// lib/client.js, and the failure mode is SILENT: the component it publishes is
// simply `undefined` at runtime, so whatever registers it skips itself and the
// feature vanishes with no error anywhere. That is how an entire settings page
// can disappear. Fail loud instead.

const compiled = readdirSync(SRC_DIR).filter((name) => name.endsWith('.js'))
const unlisted = compiled.filter((name) => !PARTS.includes(name))
if (unlisted.length > 0) {
  fail(
    `build/client contains file(s) missing from PARTS: ${unlisted.join(', ')}\n` +
      'add them to PARTS in this script — order matters (publishers before consumers).',
  )
}

// ---- 2. assembly ---------------------------------------------------------

const banner = `/*!
 * dsh-task-alerts — browser half. GENERATED by scripts/build-client.mjs — do not edit.
 * Concatenation (contract §7): ${PARTS.join(' + ')} + inlined styles.css.
 */`

const cssLiteral =
  `window.__DSA__ = window.__DSA__ || {};\n` +
  `    window.__DSA__.css = ${JSON.stringify(css)};`

const bundle = [
  banner,
  `window.__ModuleLoader__.load({`,
  `  id: '${MODULE_ID}',`,
  // The loader hands `require` to the factory as its FIRST PARAMETER — it is NOT
  // a global. Evidence: @deepseek-ai/dsh-client-modules/lib/client.js:683 does
  // `registered.factory(this.makeRequire(ownerId, edges))`, and that package's own
  // browser half opens with `factory: (require) => {`. Omitting the parameter makes
  // every module body throw "require is not defined", which the loader reports as
  // "1 entry did not activate" and treats as a FATAL web-boot failure — the app
  // could not start. Do not remove this parameter.
  `  factory: function (require) {`,
  `    try {`,
  `      return (function () {`,
  // The inner IIFE carries its own strict directive: the parts are compiled
  // scripts whose `"use strict"` prologue stops being a *directive* once it sits
  // inside a `try` block, which would silently run them in sloppy mode.
  `        "use strict";`,
  `        var React = require('react');`,
  `        ${cssLiteral}`,
  ``,
  ...sources.map(
    (part) =>
      `        /* ---- begin ${part.name} ---- */\n` +
      part.text.replace(/\s+$/, '') +
      `\n        /* ---- end ${part.name} ---- */`,
  ),
  ``,
  `        var apply = window.__DSA__ && typeof window.__DSA__.apply === 'function' ? window.__DSA__.apply : null;`,
  `        if (!apply) throw new Error('browser half did not publish window.__DSA__.apply');`,
  // Sealing the factory is NOT enough. The loader materializes the module first
  // and only then calls `apply(ctx)` in a second step, so a throw from `apply`
  // fails the entry identically ("1 entry did not activate" = fatal web boot).
  // Both steps must be sealed.
  `        return {`,
  `          inject: ['slots'],`,
  `          apply: function (ctx) {`,
  `            try {`,
  `              return apply(ctx);`,
  `            } catch (error) {`,
  `              try {`,
  `                console.error(`,
  `                  '[dsh-task-alerts] apply() failed; the alert UI is disabled, DSH boot continues',`,
  `                  error,`,
  `                );`,
  `              } catch (ignored) {}`,
  `            }`,
  `          },`,
  `        };`,
  `      })();`,
  `    } catch (error) {`,
  // Sealed containment. A fault anywhere in the browser half must degrade to a
  // no-op plugin that still ACTIVATES, so a broken alert UI can never again make
  // the whole harness unbootable.
  `      try {`,
  `        console.error(`,
  `          '[dsh-task-alerts] browser half failed to initialize; the alert UI is disabled, DSH boot continues',`,
  `          error,`,
  `        );`,
  `      } catch (ignored) {}`,
  `      return { inject: [], apply: function () {} };`,
  `    }`,
  `  }`,
  `});`,
  ``,
].join('\n')

// ---- 3. output -----------------------------------------------------------

mkdirSync(dirname(OUT_JS), { recursive: true })
writeFileSync(OUT_JS, bundle, 'utf8')
writeFileSync(OUT_DTS, CLIENT_DTS, 'utf8')

const bytes = Buffer.byteLength(bundle, 'utf8')
process.stdout.write(
  `build-client: wrote ${OUT_JS} (${bytes} bytes) from ${PARTS.join(' + ')} ` +
    `[css ${Buffer.byteLength(css, 'utf8')} bytes inlined]\n`,
)
process.stdout.write(`build-client: wrote ${OUT_DTS} (${Buffer.byteLength(CLIENT_DTS, 'utf8')} bytes)\n`)
